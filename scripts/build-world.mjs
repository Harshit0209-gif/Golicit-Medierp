// Converts world.svg (MapSVG export) into src/lib/geo/world.ts.
// Run: node scripts/build-world.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const svg = readFileSync(new URL('../world.svg', import.meta.url), 'utf8');
const W = parseFloat(svg.match(/\swidth="([\d.]+)"/)[1]);
const H = parseFloat(svg.match(/\sheight="([\d.]+)"/)[1]);

const paths = [...svg.matchAll(/<path\s+d="([^"]+)"\s+title="([^"]*)"\s+id="([^"]+)"/g)].map((m) => ({
  d: m[1],
  name: m[2],
  id: m[3],
}));

/** Parses relative-move/closepath path data into absolute polygons. */
function parse(d) {
  const tokens = d.match(/[mMzZ]|-?\d*\.?\d+(?:e[-+]?\d+)?/gi) ?? [];
  const polys = [];
  let cur = [0, 0];
  let start = [0, 0];
  let poly = null;
  let nums = [];
  let first = true;
  const flush = () => {
    for (let i = 0; i + 1 < nums.length; i += 2) {
      if (poly.length === 0 && first) cur = [nums[i], nums[i + 1]];
      else cur = [cur[0] + nums[i], cur[1] + nums[i + 1]];
      if (poly.length === 0) start = cur;
      poly.push(cur);
    }
    nums = [];
  };
  for (const t of tokens) {
    if (/[mM]/.test(t)) {
      poly = [];
      nums = [];
      polys.push(poly);
      // a new subpath after z starts relative to the previous start point
      if (!first) cur = start;
      // remember whether the next pair is the first move of the whole path
      poly._isFirst = first;
      first = false;
    } else if (/[zZ]/.test(t)) {
      // process pending numbers using the 'm' semantics
      processPending();
      cur = start;
    } else {
      nums.push(parseFloat(t));
    }
  }
  processPending();
  return polys.filter((p) => p.length > 2);

  function processPending() {
    if (!poly || nums.length === 0) return;
    for (let i = 0; i + 1 < nums.length; i += 2) {
      if (poly.length === 0 && poly._isFirst) cur = [nums[i], nums[i + 1]];
      else cur = [cur[0] + nums[i], cur[1] + nums[i + 1]];
      if (poly.length === 0) start = cur;
      poly.push(cur);
    }
    nums = [];
  }
}

const polyArea = (p) => {
  let a = 0;
  for (let i = 0; i < p.length; i++) {
    const [x1, y1] = p[i];
    const [x2, y2] = p[(i + 1) % p.length];
    a += x1 * y2 - x2 * y1;
  }
  return a / 2;
};

const centroid = (p) => {
  let a = 0, cx = 0, cy = 0;
  for (let i = 0; i < p.length; i++) {
    const [x1, y1] = p[i];
    const [x2, y2] = p[(i + 1) % p.length];
    const f = x1 * y2 - x2 * y1;
    a += f; cx += (x1 + x2) * f; cy += (y1 + y2) * f;
  }
  a /= 2;
  return Math.abs(a) < 1e-9 ? p[0] : [cx / (6 * a), cy / (6 * a)];
};

/** Drops points closer than `min` to the previous kept point (keeps shape, cuts size). */
const thin = (p, min) => {
  if (min <= 0) return p;
  const out = [p[0]];
  for (let i = 1; i < p.length - 1; i++) {
    const [lx, ly] = out[out.length - 1];
    if (Math.hypot(p[i][0] - lx, p[i][1] - ly) >= min) out.push(p[i]);
  }
  out.push(p[p.length - 1]);
  return out.length >= 3 ? out : p;
};

// Anchors set by hand where the centroid of the main landmass falls outside the country.
const OVERRIDES = { NO: [497, 240] };

const countries = paths.map(({ d, name, id }) => {
  const polys = parse(d);
  const all = polys.flat();
  const xs = all.map((p) => p[0]), ys = all.map((p) => p[1]);
  const bbox = [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
  const area = (bbox[2] - bbox[0]) * (bbox[3] - bbox[1]);
  const biggest = polys.reduce((a, b) => (Math.abs(polyArea(b)) > Math.abs(polyArea(a)) ? b : a));
  const [lx, ly] = centroid(biggest);
  const tiny = area < 40;
  const out = polys
    .map((p) => {
      const [bx0, by0, bx1, by1] = [Math.min(...p.map((q) => q[0])), Math.min(...p.map((q) => q[1])), Math.max(...p.map((q) => q[0])), Math.max(...p.map((q) => q[1]))];
      const small = (bx1 - bx0) * (by1 - by0) < 6;
      const pts = tiny ? p : small ? thin(p, 0.2) : thin(p, 0.75);
      const dp = tiny ? 2 : 1;
      return 'M' + pts.map(([x, y]) => `${+x.toFixed(dp)} ${+y.toFixed(dp)}`).join('L') + 'Z';
    })
    .join('');
  const [ox, oy] = OVERRIDES[id] ?? [lx, ly];
  return { code: id, name, d: out, labelX: +ox.toFixed(1), labelY: +oy.toFixed(1), area: Math.round(area) };
});

const ts = `/* eslint-disable */
// GENERATED by scripts/build-world.mjs from world.svg (MapSVG export). Do not edit by hand.
export interface CountryGeometry {
  /** ISO 3166-1 alpha-2 (a few territories use ISO 3166-2, e.g. "UM-DQ"). */
  code: string;
  name: string;
  /** Path data for the whole country (all parts), absolute coordinates. */
  d: string;
  /** Anchor for labels, markers and keyboard navigation: centre of the main landmass. */
  labelX: number;
  labelY: number;
  /** Bounding-box area in SVG units², decides which countries get an inline label. */
  area: number;
}

export const WORLD_VIEWBOX = '0 0 ${W} ${H}';

export const worldCountries: CountryGeometry[] = ${JSON.stringify(countries)};
`;
writeFileSync(new URL('../src/lib/geo/world.ts', import.meta.url), ts);
console.log(countries.length, 'countries,', (ts.length / 1024).toFixed(0), 'KB');
const pick = ['US','NO','ID','SG','MT','GB','AE','IN','FR','RU'];
for (const c of countries.filter((c) => pick.includes(c.code))) console.log(c.code, c.labelX, c.labelY, c.area);
